// ─────────────────────────────────────────────────────────────────────────────
// images.mjs: the photos of the current site (reference/current-site/images, pulled 11/11/2026 with
// Adryan's OK) and, later, the client's own (reference/uploads) → public/images as WebP at the size they
// are shown (≤ 1920) + a -sm for phones, and src/data/images.gen.ts with their real pixel sizes.
// Folders are flattened: gym/hip-throw/hipthrow3.webp → hipthrow3. Run: `npm run images`.
// ─────────────────────────────────────────────────────────────────────────────
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import sharp from 'sharp'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const out = path.join(root, 'public', 'images')
fs.mkdirSync(out, { recursive: true })
const SOURCES = ['reference/current-site/images', 'reference/uploads'].map((d) => path.join(root, d)).filter((d) => fs.existsSync(d))
const SKIP = /^(instagram|facebook)$/ // the old site's social icons
// files Adryan prepared himself (12/11: the coach portraits, the kid cutout): copied as they are, one size,
// never re-encoded (re-encoding blurs them; see the Cristyan coach cutout)
const KEEP = /^(ricardo_barros|connor_ohai|eric_rubio|abigail_gordon|kid_cutout)$/

const walk = (d) => fs.readdirSync(d, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(path.join(d, e.name)) : [path.join(d, e.name)]))
const key = (f) => path.basename(f).replace(/\.(jpe?g|png|webp)$/i, '').replace(/[^a-z0-9]+/gi, '_').replace(/^_|_$/g, '').toLowerCase()

const sizes = {}
for (const dir of SOURCES) {
  for (const src of walk(dir).filter((x) => /\.(jpe?g|png|webp)$/i.test(x))) {
    const name = key(src)
    if (SKIP.test(name)) continue
    const meta = await sharp(src).metadata()
    if (/^logo/.test(name)) {
      const info = await sharp(src).resize({ width: Math.min(640, meta.width) }).png({ compressionLevel: 9 }).toFile(path.join(out, `${name}.png`))
      sizes[name] = { w: info.width, h: info.height, ext: 'png' }
      continue
    }
    if (KEEP.test(name)) {
      const dst = path.join(out, `${name}.webp`)
      if (/\.webp$/i.test(src)) fs.copyFileSync(src, dst)
      else await sharp(src).webp({ quality: 95, effort: 6 }).toFile(dst)
      fs.rmSync(path.join(out, `${name}-sm.webp`), { force: true })
      sizes[name] = { w: meta.width, h: meta.height }
      continue
    }
    const w = Math.min(1920, meta.width)
    const info = await sharp(src).rotate().resize({ width: w }).webp({ quality: 76, effort: 6 }).toFile(path.join(out, `${name}.webp`))
    const sm = Math.min(w, meta.width > 1000 ? 820 : 480)
    await sharp(src).rotate().resize({ width: sm }).webp({ quality: 72, effort: 6 }).toFile(path.join(out, `${name}-sm.webp`))
    sizes[name] = { w: info.width, h: info.height, sm }
  }
}
const sorted = Object.fromEntries(Object.entries(sizes).sort(([a], [b]) => a.localeCompare(b)))
fs.writeFileSync(path.join(root, 'src', 'data', 'images.gen.ts'), `// generated by scripts/images.mjs\nexport const IMG = ${JSON.stringify(sorted, null, 2)} as const\n`)
console.log(`images: ${Object.keys(sizes).length} → public/images`)
